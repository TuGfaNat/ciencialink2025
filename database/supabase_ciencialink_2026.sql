-- 1. TABLA: 8 COMISIONES TECNOLÓGICAS
create table if not exists commissions (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  short_name text not null,
  description text not null,
  color text not null, -- Código HEX de color de la comisión
  icon text not null,
  leader_name text not null,
  leader_role text not null,
  leader_avatar text,
  members_count integer default 0,
  active_projects_count integer default 0,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. TABLA: MURO INTERACTIVO DE LAS COMISIONES
create table if not exists commission_wall_posts (
  id bigint generated by default as identity primary key,
  commission_slug text references commissions(slug) on delete cascade,
  author_name text not null,
  author_role text not null,
  content text not null,
  tags text[] default '{}',
  likes_count integer default 0,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. TABLA: REPOSITORIO CIENTÍFICO (ARTÍCULOS Y PAPERS)
create table if not exists scientific_papers (
  id bigint generated by default as identity primary key,
  title text not null,
  abstract text not null,
  authors text not null,
  commission_slug text references commissions(slug) on delete set null,
  category text not null, -- 'Investigación', 'Revisión', 'Divulgación', 'Tesis'
  published_date text not null,
  doi text,
  pdf_url text,
  downloads_count integer default 0,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. TABLA: PORTAFOLIO DE PROYECTOS POR ÁREAS
create table if not exists projects (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  commission_slug text references commissions(slug) on delete set null,
  stage text not null, -- 'Ideación', 'Desarrollo', 'Pruebas', 'Completado'
  progress_pct integer check (progress_pct >= 0 and progress_pct <= 100) default 0,
  image_url text,
  leader text not null,
  tags text[] default '{}',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 5. TABLA: MEMORIA INSTITUCIONAL (TIMELINE DE HITOS)
create table if not exists milestones (
  id bigint generated by default as identity primary key,
  year text not null,
  date_str text not null,
  title text not null,
  description text not null,
  category text not null, -- 'Evento', 'Convenio', 'Logro', 'Expansión'
  impact_metric text,
  image_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 6. TABLA: NEWSLETTER STEM / REGISTRO DE MIEMBROS (LEAD MAGNET)
create table if not exists newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text unique not null,
  full_name text,
  interest_area text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

